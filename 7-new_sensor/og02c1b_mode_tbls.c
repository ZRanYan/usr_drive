/**
 * @brief 配置MAX96717管脚输出24MHz时钟信号
 * 
 * @param priv 
 * @return int 
 */
static int og02c1b_power_on(struct nv_sony_sensor *priv)
{
    int ret = 0;
    struct i2c_client *client = priv->i2c_client;
    u8 addr = MAX96717_OG02_ALTER_ADDR_BASE + priv->des_link;
    u8 i = 0;
    for (i = 0; i < 4; i++)
    {
        const struct reg_cfg_cmd *item = &g_clk_config_table[0][i];
        if (item->op == 0x80)
        {
            ret = gmsl_iic_write(client, addr, item->reg, item->data);
        }
        else if (item->op == 0x81)
        {
            ret = device_reg_update_bits(client, addr, \
                                item->reg, item->mask, item->data);
        }
        if (ret < 0) return ret;
    }
    msleep_range(10);
    //加载驱动的时候拉高MFP7->XSHUTDOWN管脚
    ret = gmsl_iic_write(client, addr, MAX96717_GPIO7_A_ADDR_BASE, 0x90);
    msleep_range(100);
    // //测试MFP8的接口和VTG的接口
    ret = gmsl_iic_write(client, addr, 0x0005, 0x00);
    ret = gmsl_iic_write(client, addr, 0x02d6, 0x9B);
    ret = gmsl_iic_write(client, addr, 0x02d7, 0xA0);
    // msleep_range(10);
    // ret = gmsl_iic_write(client, addr, 0x02d6, 0x00);
    return ret;
}

static int og02c1b_power_off(struct nv_sony_sensor *priv)
{
    int ret = 0;
    struct i2c_client *client = priv->i2c_client;
    u8 addr = MAX96717_OG05_ALTER_ADDR_BASE + priv->des_link;
    u8 i = 0;
     for (i = 0; i < 5; i++)
    {
        const struct reg_cfg_cmd *item = &g_clk_config_table[1][i];
        if (item->op == 0x80)
        {
            ret = gmsl_iic_write(client, addr, item->reg, item->data);
        }
        else if (item->op == 0x81)
        {
            ret = device_reg_update_bits(client, addr, \
                                item->reg, item->mask, item->data);
        }
        if (ret < 0) return ret;
    }
    msleep_range(1);
    ret = gmsl_iic_write(client, addr, MAX96717_GPIO7_A_ADDR_BASE, 0x80); //配置管脚MFP0输出
    return ret;
}

static int og02c1b_board_setup(struct nv_sony_sensor *priv, MODE_TYPE mode)
{
    int err = 0;
	u8 buf[3] = {0};
	u8 val;
    u8 ser_alias_addr;
    struct i2c_client *client = priv->i2c_client;
    z_max96724_lock_link(priv->dser_dev);
    vc_info(&client->dev, "priv->des_link:%d \r\n", priv->des_link);
    err = z_max96724_check_link_status(priv->dser_dev, priv->des_link);
    if (err)
    {
        z_max96724_unlock_link(priv->dser_dev);
        vc_err(&client->dev, " link_%c is occupied err:%d\n", 'A' + priv->des_link, err);
        err = -EINVAL;
    }
    z_max96724_monopolize_link(priv->dser_dev, priv->des_link);
    mdelay(50);
    gmsl_iic_write(client, 0x40, 0x0000, (MAX96717_OG02_ALTER_ADDR_BASE + priv->des_link) << 1);
    mdelay(50);
    //读取max6717的id编号
    err = gmsl_iic_read(client, MAX96717_OG02_ALTER_ADDR_BASE+priv->des_link, MAX96717_DEV_ID, &val);
    vc_info(&client->dev, "ret:%d MAX96717_DEV_ID:0x%x\n", err, val);
    if (err || (val != 0x91 && val != 0xbf))
    {
        vc_err(&client->dev, "access 's max969717 failed\n");
        err = -EINVAL;
        goto ERR_EXIT;
    }
    err = og02c1b_power_on(priv);
    if(err)
    {
        vc_err(&client->dev, "og02c1b_power_on failed!\n");
        err = -EINVAL;
        goto ERR_EXIT;
    }
    mdelay(100);
    //读取sensor的id编号
    err = gmsl_iic_read(client, priv->def_addr, 0x300A, &buf[0]);
	err |= gmsl_iic_read(client, priv->def_addr, 0x300B, &buf[1]);
	err |= gmsl_iic_read(client, priv->def_addr, 0x300C, &buf[2]);
	vc_info(&client->dev,"==val:0x%x  0x%x 0x%x\r\n", buf[0], buf[1], buf[2]);
	if (err || buf[0] != 0xc7 || buf[1] != 0x02 || buf[2] != 0x43) {
		vc_err(&client->dev, "read sensor id failed\n");
		goto ERR_EXIT;
	}
    ser_alias_addr = MAX96717_OG02_ALTER_ADDR_BASE+priv->des_link;
    vc_info(&client->dev, "ser_alias_addr:0x%x act_addr:0x%x def_addr:0x%x \r\n", ser_alias_addr, priv->act_addr, priv->def_addr);
    gmsl_iic_write(client, ser_alias_addr, 0x0044, priv->act_addr<<1); //dst addr,在地址映射槽位B，用于配置I2C透明传输的地址重映射
	gmsl_iic_write(client, ser_alias_addr, 0x0045, priv->def_addr<<1); //src addr, original sensor addr

    gmsl_iic_write(client, ser_alias_addr ,0x0330, 0x00); // MIPI_RX : MIPI_RX0 | (Default) RSVD (Port Configuration): 1x4
    gmsl_iic_write(client, ser_alias_addr ,0x0383, 0x00); //Disable tunneling mode

    vc_info(&client->dev, "num_ser_csi_lanes:%d \r\n", priv->g_ctx.num_ser_csi_lanes);
    gmsl_iic_write(client, ser_alias_addr ,0x0331, (((priv->g_ctx.num_ser_csi_lanes-1)<<4))); //配置寄存器MIPI_RX，

    gmsl_iic_write(client, ser_alias_addr, 0x0311, 0x40);//Start video pipe Z from CSI port
    gmsl_iic_write(client, ser_alias_addr, 0x0318, 0x40 | GMSL_CSI_DT_RAW_8); //选择使能RAW10的数据类型(0x2B)通过video pipeline
    gmsl_iic_write(client, ser_alias_addr, 0x0312, 0x04); //Send 8-bit as 16-bit

    gmsl_iic_write(client, ser_alias_addr, 0x031E, 0x20 | 0x10);  //BPP = 10 on pipe Z,enable soft_bppz_en

    gmsl_iic_write(client, ser_alias_addr, 0x007b, 0x30+priv->des_link); //CFGI INFOFR RCSI-2视频流进入MAX96717以后，如何打包成GMSL视频数据
    gmsl_iic_write(client, ser_alias_addr, 0x0093, 0x30+priv->des_link); //CFGL GPIO
    gmsl_iic_write(client, ser_alias_addr, 0x00a3, 0x30+priv->des_link);//CFGL IIC_X
    gmsl_iic_write(client, ser_alias_addr, 0x00ab, 0x30+priv->des_link);//CFGL IIC_Y

    gmsl_iic_write(client, ser_alias_addr, 0x005B, 0x00); //Stream ID for packets from this channel
    gmsl_iic_write(client, ser_alias_addr ,0x0308, 0x64);//开启enable_line_info,和START_PORTB

    // //输出MFP8管脚为输入高阻
    // err = gmsl_iic_write(client, ser_alias_addr, 0x02D6, 0x81);
    // err = gmsl_iic_write(client, ser_alias_addr, 0x02D6, 0x28);

    z_max96724_enable_link(priv->dser_dev, priv->des_link);
ERR_EXIT:
    z_max96724_restore_link(priv->dser_dev);
    z_max96724_unlock_link(priv->dser_dev);
    return err;
}
